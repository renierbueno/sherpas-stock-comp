// Traceability: every AC and EV of the spec against the tests whose titles name it.
// Usage: npm run trace            (prints the table; fails if the spec's Test cells or the index's
//                                  Traceability block differ from the tests; pending allowed while building)
//        npm run trace -- --strict (also fails if any criterion is pending)
//        npm run trace -- --write  (writes the Test cells of every spec file and the index block)
import { readFileSync, readdirSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { SPEC_ONLY } from '../src/model/scope';

const root = join(import.meta.dirname, '..');
const specDir = join(root, '..', 'docs', 'spec');
const testDirs = ['tests/unit', 'tests/component', 'e2e'].map((d) => join(root, d));

const ids = new Map<string, string>(); // id -> feature
const titles = new Map<string, string>(); // feature -> title from the spec file's heading
titles.set('G', 'G · Rules for every feature');
const specFiles = readdirSync(specDir).filter((f) => f.endsWith('.md'));
for (const f of specFiles) {
  const h = readFileSync(join(specDir, f), 'utf8').match(/^# (F-([A-Z]) · .+)$/m);
  if (h) titles.set(h[2], h[1]);
  for (const m of readFileSync(join(specDir, f), 'utf8').matchAll(/^\| ((?:AC|EV)-([A-Z])-\d+) \|/gm)) ids.set(m[1], m[2]);
}

const tests = new Map<string, string[]>(); // id -> test references
for (const dir of testDirs) {
  let files: string[] = [];
  try { files = readdirSync(dir).filter((f) => /\.(test|spec)\.tsx?$/.test(f)); } catch { continue; }
  for (const f of files) {
    const src = readFileSync(join(dir, f), 'utf8');
    for (const m of src.matchAll(/\b(?:it|test)\(\s*['"`]([^'"`]+)['"`]/g)) {
      const title = m[1];
      const kind = dir.endsWith('e2e') ? 'e2e' : dir.endsWith('component') ? 'component' : 'unit';
      for (const id of title.match(/\b(?:AC|EV)-[A-Z]-\d+\b/g) ?? []) {
        tests.set(id, [...(tests.get(id) ?? []), `${kind}:${f.replace(/\.(test|spec)\.tsx?$/, '')} "${title.split(' · ').pop()}"`]);
      }
    }
  }
}

const args = process.argv.slice(2);
const order = ['G', 'A', 'B', 'C', 'D', 'E', 'F'];
const rows = [...ids.entries()].sort(([a, fa], [b, fb]) => order.indexOf(fa) - order.indexOf(fb) || a.localeCompare(b, 'en', { numeric: true }));
let pending = 0;
const counts = { tested: 0, specOnly: 0, pending: 0 };
const kinds = ['unit', 'component', 'e2e'];
const byKind = (a: string, b: string) => kinds.indexOf(a.split(' ')[0]) - kinds.indexOf(b.split(' ')[0]) || a.localeCompare(b);

const out: string[] = [];
const cells = new Map<string, string>(); // id -> the spec's Test cell
const byFeature = new Map<string, { ids: number; tested: number; specOnly: string[]; refs: Set<string> }>();
for (const [id, feature] of rows) {
  const t = tests.get(id);
  const status = t ? 'tested' : SPEC_ONLY[id] ? `spec only: ${SPEC_ONLY[id]}` : 'pending';
  if (t) counts.tested++; else if (SPEC_ONLY[id]) counts.specOnly++; else { counts.pending++; pending++; }
  const refs = t ? [...new Set(t.map((r) => r.split(' "')[0]))].sort((a, b) => byKind(a.replace(':', ' '), b.replace(':', ' '))) : [];
  out.push(`${id.padEnd(8)} ${status.padEnd(9)} ${refs.join(', ')}`);
  cells.set(id, t ? refs.map((r) => r.replace(':', ' ')).join(', ') : SPEC_ONLY[id] ? 'spec only (see index)' : '(F6)');
  const g = byFeature.get(feature) ?? { ids: 0, tested: 0, specOnly: [], refs: new Set<string>() };
  g.ids++; if (t) g.tested++; else if (SPEC_ONLY[id]) g.specOnly.push(id);
  refs.forEach((r) => g.refs.add(r.replace(':', ' ')));
  byFeature.set(feature, g);
}

// The index block: one row per feature, then each criterion left as spec only with its reason.
const block = [
  '<!-- trace:start · generated by `npm run trace -- --write`; do not edit by hand -->',
  '| Feature | Requirements and events | Tested | Spec only | Test files |',
  '|---|---|---|---|---|',
  ...order.filter((f) => byFeature.has(f)).map((f) => {
    const g = byFeature.get(f)!;
    return `| ${titles.get(f) ?? f} | ${g.ids} | ${g.tested} | ${g.specOnly.length} | ${[...g.refs].sort(byKind).join(', ')} |`;
  }),
  `| **Total** | ${ids.size} | ${counts.tested} | ${counts.specOnly} | |`,
  '',
  'Spec only, with the reason each is not built in the prototype (D-063):',
  '',
  '| ID | Reason |',
  '|---|---|',
  ...rows.filter(([id]) => !tests.has(id) && SPEC_ONLY[id]).map(([id]) => `| \`${id}\` | ${SPEC_ONLY[id].trim()} |`),
  '',
  'Each requirement row in the feature files names its tests in the Test column: `unit` and `component` are files in `prototype/tests/`, `e2e` is the browser walk in `prototype/e2e/`.',
  '<!-- trace:end -->',
].join('\n');

// Spec files as they should read: each AC and EV row's last cell, and the index block.
const stale: string[] = [];
for (const f of specFiles) {
  const path = join(specDir, f);
  const src = readFileSync(path, 'utf8');
  let next = src.replace(/^(\| ((?:AC|EV)-[A-Z]-\d+) \|.*\| )[^|]*( \|)$/gm, (line, head, id, tail) => (cells.has(id) ? `${head}${cells.get(id)}${tail}` : line));
  if (f === '00_index.md') next = next.replace(/<!-- trace:start[\s\S]*?<!-- trace:end -->/, block);
  if (next !== src) { if (args.includes('--write')) writeFileSync(path, next); else stale.push(f); }
}
console.log(out.join('\n'));
console.log(`\n${ids.size} criteria and events · ${counts.tested} tested · ${counts.specOnly} spec only · ${counts.pending} pending`);
const unknown = [...tests.keys()].filter((id) => !ids.has(id));
if (unknown.length) { console.error(`Test titles name IDs not in the spec: ${unknown.join(', ')}`); process.exit(1); }
if (stale.length) { console.error(`Spec Test cells or the index's Traceability block are out of date in ${stale.join(', ')}: run npm run trace -- --write`); process.exit(1); }
if (args.includes('--strict') && pending > 0) process.exit(1);
